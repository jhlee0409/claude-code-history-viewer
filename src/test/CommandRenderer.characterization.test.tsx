import { fireEvent, render } from "@testing-library/react";
import { describe, expect, it, vi } from "vitest";
import { CommandRenderer } from "../components/contentRenderer/CommandRenderer";
import { ExpandKeyProvider } from "../contexts/CaptureExpandContext";

vi.mock("react-i18next", () => ({
  useTranslation: () => ({
    t: (key: string) => key,
  }),
  initReactI18next: {
    type: "3rdParty",
    init: () => {},
  },
}));

/**
 * Characterization fixtures: CommandRenderer's rendered DOM must stay
 * identical when its parsing moves into `parseCommandMessage`.
 */
const FIXTURES: Record<string, string> = {
  nameMessageArgs:
    "<command-message>review is running…</command-message>\n<command-name>/review</command-name>\n<command-args>PR 42 --strict</command-args>",
  redundantMessage:
    "<command-name>/cost</command-name>\n<command-message>cost</command-message>\n<command-args></command-args>",
  nameWithLocalStdout:
    "<command-name>/cost</command-name>\n<local-command-stdout>Total cost: $0.42\nDuration: 3m</local-command-stdout>",
  standaloneLocalStdout:
    "<local-command-stdout>\u001b[1mCompacted\u001b[22m (ctrl+o to see full summary)</local-command-stdout>",
  caveatOnly:
    "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>",
  stdoutStderrAndText:
    "<bash-stdout>ok\nline 2</bash-stdout><bash-stderr>warning: x</bash-stderr>\nSome **remaining** text",
  plainText: "Just a normal message without tags",
  empty: "<command-args>   </command-args>",
};

function renderFixture(text: string, searchQuery?: string) {
  return render(
    <ExpandKeyProvider value="command-renderer-test">
      <CommandRenderer text={text} searchQuery={searchQuery} />
    </ExpandKeyProvider>,
  );
}

describe("CommandRenderer output (characterization)", () => {
  for (const [name, text] of Object.entries(FIXTURES)) {
    it(`renders ${name} unchanged (collapsed and expanded)`, () => {
      const { container } = renderFixture(text);
      expect(container.innerHTML).toMatchSnapshot("collapsed");

      const toggle = container.querySelector<HTMLButtonElement>(
        'button[aria-expanded="false"]',
      );
      if (toggle) fireEvent.click(toggle);
      expect(container.innerHTML).toMatchSnapshot("expanded");
    });
  }

  it("renders search highlighting unchanged", () => {
    const { container } = renderFixture(FIXTURES.nameMessageArgs!, "strict");
    expect(container.innerHTML).toMatchSnapshot();
  });
});
