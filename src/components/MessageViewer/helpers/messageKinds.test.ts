import { describe, expect, it } from "vitest";
import type { ClaudeMessage } from "../../../types";
import {
  classifyMessage,
  getMessageKind,
  isTaskNotification,
  parseTaskNotification,
  parseTaskNotifications,
  isTurnStart,
} from "./messageKinds";

const makeMessage = (overrides: Record<string, unknown>): ClaudeMessage => ({
  uuid: "message",
  type: "user",
  role: "user",
  timestamp: "2026-09-26T06:29:32.477Z",
  content: "",
  ...overrides,
} as unknown as ClaudeMessage);

const TASK_NOTIFICATION = [
  "<task-notification>",
  "<task-id>ad2512cc64c5db295</task-id>",
  "<tool-use-id>toolu_01ATyzGrFtsVZ7xDtZbu2Ji6</tool-use-id>",
  "<output-file>C:\\Users\\me\\AppData\\Local\\Temp\\claude\\tasks\\ad2512cc64c5db295.output</output-file>",
  "<status>completed</status>",
  '<summary>Agent "W6 Starlight 0.42.4 upgrade" finished</summary>',
  "</task-notification>",
].join("\n");

describe("getMessageKind", () => {
  describe("user-type messages", () => {
    it("treats typed text as a prompt", () => {
      expect(getMessageKind(makeMessage({ content: "Scrub for pii. Then push to gh." }))).toBe("prompt");
      expect(getMessageKind(makeMessage({
        content: [{ type: "text", text: "I agree with your recommendations." }],
      }))).toBe("prompt");
    });

    it("treats a prompt that mentions tags inline as a prompt", () => {
      expect(getMessageKind(makeMessage({
        content: "Why does <task-notification> show up in the panel?",
      }))).toBe("prompt");
    });

    it("treats a <task-notification> as an agent update", () => {
      expect(getMessageKind(makeMessage({ content: TASK_NOTIFICATION }))).toBe("agent-update");
      expect(getMessageKind(makeMessage({
        content: [{ type: "text", text: TASK_NOTIFICATION }],
      }))).toBe("agent-update");
    });

    it("keeps a notification with the client's injected preamble as an agent update", () => {
      // Claude Code prepends this header to background-task events, so text
      // around a notification does not mean the user typed it.
      const text = [
        "[SYSTEM NOTIFICATION - NOT USER INPUT]",
        "This is an automated background-task event, NOT a message from the user.",
        TASK_NOTIFICATION,
      ].join("\n");
      expect(getMessageKind(makeMessage({ content: [{ type: "text", text }] }))).toBe("agent-update");
    });

    it("treats a slash command and its local output as a command", () => {
      expect(getMessageKind(makeMessage({
        content: "<command-message>plab-wrap-session</command-message>\n<command-name>/plab-wrap-session</command-name>",
      }))).toBe("command");
      expect(getMessageKind(makeMessage({
        content: "<local-command-stdout>Total cost: $0.42</local-command-stdout>",
      }))).toBe("command");
    });

    it("treats text wrapped in one injected tag as context", () => {
      expect(getMessageKind(makeMessage({
        content: "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>",
      }))).toBe("context");
      expect(getMessageKind(makeMessage({
        content: "<environment_context>\n  <cwd>/repo</cwd>\n</environment_context>",
        provider: "codex",
      }))).toBe("context");
    });

    it("treats a pasted block with no typed text as a prompt", () => {
      expect(getMessageKind(makeMessage({
        content: "<pasted_content>\nstack trace here\n</pasted_content>",
      }))).toBe("prompt");
    });

    it("prefers typed text over an injected block in the same message", () => {
      const info = classifyMessage(makeMessage({
        content: [
          { type: "text", text: "<system-reminder>\nToday is Friday.\n</system-reminder>" },
          { type: "text", text: "Scrub for pii" },
        ],
      }));
      expect(info.kind).toBe("prompt");
      expect(info.text).toBe("Scrub for pii");
    });

    it("treats a compaction summary as context", () => {
      expect(getMessageKind(makeMessage({
        content: "This session is being continued from a previous conversation that ran out of context. The summary below covers the earlier portion.",
      }))).toBe("context");
    });

    it("returns the parsed notification with an agent update", () => {
      const info = classifyMessage(makeMessage({ content: TASK_NOTIFICATION }));
      expect(info.notification).toEqual({
        taskId: "ad2512cc64c5db295",
        status: "completed",
        summary: 'Agent "W6 Starlight 0.42.4 upgrade" finished',
      });
    });

    it("treats an interruption marker as context", () => {
      expect(getMessageKind(makeMessage({ content: "[Request interrupted by user]" }))).toBe("context");
      expect(getMessageKind(makeMessage({
        content: [{ type: "text", text: "[Request interrupted by user for tool use]" }],
      }))).toBe("context");
    });

    it("treats a tool-result carrier with no text as a tool row", () => {
      expect(getMessageKind(makeMessage({
        content: [{ type: "tool_result", tool_use_id: "toolu_1", content: "ok" }],
      }))).toBe("tool");
      expect(getMessageKind(makeMessage({
        content: [],
        toolUseResult: { stdout: "ok" },
      }))).toBe("tool");
    });

    it("treats a tool-result record with client-appended text as a tool row", () => {
      // ToolSearch appends "Tool loaded." to its result. The backend moves the
      // tool_result block into its call, leaving the text and the record's
      // toolUseResult behind.
      const info = classifyMessage(makeMessage({
        content: [{ type: "text", text: "Tool loaded." }],
        toolUseResult: { matches: ["WebFetch"], query: "select:WebFetch" },
      }));
      expect(info).toEqual({ kind: "tool", text: null });
    });

    it("keeps a fork's directive beside an unmerged tool_result as a prompt", () => {
      // A fork's task arrives with the parent's tool_result but no
      // toolUseResult. It is the fork's prompt, like a regular subagent's task.
      expect(getMessageKind(makeMessage({
        content: [
          { type: "tool_result", tool_use_id: "toolu_parent", content: "Agent started" },
          { type: "text", text: "<fork-boilerplate>\nYou are a worker fork.\n</fork-boilerplate>\n\nYour directive: audit the parser." },
        ],
      }))).toBe("prompt");
    });

    it("treats an image-only message as a prompt", () => {
      expect(getMessageKind(makeMessage({
        content: [{ type: "image", source: { type: "base64", media_type: "image/png", data: "AAAA" } }],
      }))).toBe("prompt");
    });
  });

  describe("other message types", () => {
    it("treats assistant text as a reply", () => {
      expect(getMessageKind(makeMessage({
        type: "assistant",
        role: "assistant",
        content: [{ type: "text", text: "Scrubbing first, then the LICENSE." }],
      }))).toBe("reply");
    });

    it("treats an assistant message with only tool calls as a tool row", () => {
      expect(getMessageKind(makeMessage({
        type: "assistant",
        role: "assistant",
        content: [{ type: "tool_use", id: "toolu_2", name: "Bash", input: {} }],
      }))).toBe("tool");
    });

    it("maps system and summary messages to their own kinds", () => {
      expect(getMessageKind(makeMessage({ type: "system", subtype: "away_summary", content: "Recap" }))).toBe("system");
      const summary = classifyMessage(makeMessage({ type: "summary", summary: "Session summary" }));
      expect(summary).toEqual({ kind: "summary", text: "Session summary" });
    });
  });
});

describe("isTurnStart", () => {
  const startsTurn = (overrides: Record<string, unknown>) =>
    isTurnStart(classifyMessage(makeMessage(overrides)));

  it("starts a turn at a typed prompt or a slash-command invocation", () => {
    expect(startsTurn({ content: "Scrub for pii" })).toBe(true);
    expect(startsTurn({
      content: "<command-message>wrap</command-message>\n<command-name>/wrap</command-name>",
    })).toBe(true);
  });

  it("does not start a turn at a local command's output", () => {
    // The output follows its invocation; counting both would stop twice.
    expect(startsTurn({
      content: "<local-command-stdout>Total cost: $0.42</local-command-stdout>",
    })).toBe(false);
  });

  it("does not start a turn at rows the user did not type", () => {
    expect(startsTurn({ content: TASK_NOTIFICATION })).toBe(false);
    expect(startsTurn({ content: "<system-reminder>Today is Friday.</system-reminder>" })).toBe(false);
    expect(startsTurn({
      type: "assistant",
      role: "assistant",
      content: [{ type: "text", text: "Done." }],
    })).toBe(false);
  });
});

describe("isTaskNotification", () => {
  it("needs a complete block, not a mention", () => {
    expect(isTaskNotification(TASK_NOTIFICATION)).toBe(true);
    expect(isTaskNotification("Why does <task-notification> show up?")).toBe(false);
  });
});

describe("parseTaskNotifications", () => {
  it("reads every block in order, including the result", () => {
    const text = [
      "<task-notification><task-id>a</task-id><status>completed</status><result>done</result></task-notification>",
      "<task-notification><task-id>b</task-id><status>failed</status></task-notification>",
    ].join("\n");
    expect(parseTaskNotifications(text)).toEqual([
      { taskId: "a", status: "completed", summary: undefined, result: "done" },
      { taskId: "b", status: "failed", summary: undefined, result: undefined },
    ]);
  });
});

describe("parseTaskNotification", () => {
  it("reads the status and the human-readable summary", () => {
    expect(parseTaskNotification(TASK_NOTIFICATION)).toEqual({
      taskId: "ad2512cc64c5db295",
      status: "completed",
      summary: 'Agent "W6 Starlight 0.42.4 upgrade" finished',
    });
  });

  it("returns null for text without a notification", () => {
    expect(parseTaskNotification("Scrub for pii.")).toBeNull();
  });

  it("tolerates missing fields", () => {
    expect(parseTaskNotification("<task-notification><task-id>agent-1</task-id></task-notification>")).toEqual({
      taskId: "agent-1",
      status: undefined,
      summary: undefined,
    });
  });
});
